
const mongoose = require("mongoose");

// Next of kin information.
// A patient can have multiple next-of-kin records.
const nextOfKinSchema = new mongoose.Schema(
  {
    firstName: { type: String, trim: true },
    middleName: { type: String, trim: true },
    lastName: { type: String, trim: true },
    address: { type: String, trim: true },
    phone: { type: String, trim: true },
    email: { type: String, trim: true, lowercase: true },
    relationship: { type: String, trim: true },
    nin: { type: String, trim: true },
  },
  { timestamps: true }
);

// Each visit can have its own vital-sign readings.
// Previous readings are preserved when the patient returns.

const vitalSchema = new mongoose.Schema(
  {
    // Date and time the measurements were taken.
    recordedAt: {
      type: Date,
      default: Date.now,
      required: true,
    },

    // Blood pressure, e.g. 120/80 mmHg.
    bloodPressure: {
      type: String,
      trim: true,
    },

    // Body measurements.
    weight: {
      type: Number,
      min: 0,
    },

    height: {
      type: Number,
      min: 0,
    },

    // Body temperature in Celsius.
    temperature: {
      type: Number,
      min: 0,
    },

    // Heart rate in beats per minute.
    pulse: {
      type: Number,
      min: 0,
    },

    // Breaths per minute.
    respiratoryRate: {
      type: Number,
      min: 0,
    },

    // Blood glucose reading.
    bloodGlucose: {
      type: Number,
      min: 0,
    },

    // Unit used for the glucose reading.
    bloodGlucoseUnit: {
      type: String,
      enum: ["mmol/L", "mg/dL"],
    },

    // Oxygen saturation as a percentage.
    oxygenSaturation: {
      type: Number,
      min: 0,
      max: 100,
    },
    bmi: {
      type: Number,
      min: 0,
  },
  },
  { timestamps: true }
);

// Main patient schema
const patientSchema = new mongoose.Schema(
  {
    // Hospital that owns this patient record.
    hospital: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Hospital",
      required: true,
      index: true,
    },

    // Unique patient ID generated by the backend.
    patientId: {
      type: String,
      trim: true,
      uppercase: true,
    },

    // Patient names
    firstName: { type: String, trim: true },
    middleName: { type: String, trim: true },
    lastName: { type: String, trim: true },

    // Kept for compatibility with existing controller/frontend code.
    name: {
      type: String,
      required: true,
      trim: true,
    },

    // Patient identification and contact details
    nin: { type: String, trim: true },

    // Date of birth is the source of truth for new patient records.
    // Optional at model level to support older records.
    dob: {
      type: Date,
      validate: {
        validator: function (value) {
          return !value || value <= new Date();
        },
        message: "Date of birth cannot be in the future.",
      },
    },

    // Legacy age field.
    // Retained for existing records that do not have a DOB.
    age: {
      type: Number,
      min: 0,
      max: 120,
    },

    gender: {
      type: String,
      lowercase: true,
      enum: ["male", "female"],
      required: true,
    },

    email: { type: String, trim: true, lowercase: true },
    phone: { type: String, trim: true },
    address: { type: String, trim: true },
    stateOfOrigin: { type: String, trim: true },
    lgaOfOrigin: { type: String, trim: true },

    // Medical information
    bloodGroup: {
      type: String,
      enum: ["A+", "A-", "B+", "B-", "AB+", "AB-", "O+", "O-"],
    },

    genotype: {
      type: String,
      enum: ["AA", "AS", "AC", "SS", "SC", "CC"],
    },

    // Multiple next-of-kin contacts
    nextOfKin: [nextOfKinSchema],

    // Visit history
    dateOfVisits: [{ type: Date }],

    // Historical vital-sign readings
    vitals: [vitalSchema],

    diagnosis: { type: String },
    treatment: { type: String },
    notes: { type: String },
    attachments: [String],
  },
  { timestamps: true }
);

// Patient IDs must be unique within each hospital.
patientSchema.index(
  { hospital: 1, patientId: 1 },
  {
    unique: true,
    partialFilterExpression: {
      patientId: { $type: "string" },
    },
  }
);

// NIN must be unique within each hospital when supplied.
patientSchema.index(
  { hospital: 1, nin: 1 },
  {
    unique: true,
    partialFilterExpression: {
      nin: { $type: "string" },
    },
  }
);

module.exports =
  mongoose.models.Patient || mongoose.model("Patient", patientSchema);