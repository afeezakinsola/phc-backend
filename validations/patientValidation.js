const Joi = require("joi");

const visitDate = Joi.date().iso();

// Validate DOB as YYYY-MM-DD without introducing timezone problems.
const dobSchema = Joi.string()
  .pattern(/^\d{4}-\d{2}-\d{2}$/)
  .custom((value, helpers) => {
    const [year, month, day] = value.split("-").map(Number);

    // Check that the date actually exists.
    const date = new Date(Date.UTC(year, month - 1, day));

    if (
      date.getUTCFullYear() !== year ||
      date.getUTCMonth() !== month - 1 ||
      date.getUTCDate() !== day
    ) {
      return helpers.error("date.invalid");
    }

    // A patient's date of birth cannot be in the future.
    const today = new Date();
    const todayUTC = Date.UTC(
      today.getUTCFullYear(),
      today.getUTCMonth(),
      today.getUTCDate()
    );

    if (date.getTime() > todayUTC) {
      return helpers.error("date.future");
    }

    return value;
  })
  .messages({
    "string.pattern.base": "Date of birth must use YYYY-MM-DD format.",
    "date.invalid": "Please provide a valid date of birth.",
    "date.future": "Date of birth cannot be in the future.",
  });

const nextOfKinSchema = Joi.object({
  firstName: Joi.string().trim().min(2).max(50).required(),
  middleName: Joi.string().trim().max(50).allow(""),
  lastName: Joi.string().trim().min(2).max(50).required(),
  address: Joi.string().trim().min(3).required(),
  phone: Joi.string().trim().pattern(/^[0-9]{11}$/).required(),  
  email: Joi.string().trim().lowercase().email().allow(""),
  relationship: Joi.string().trim().min(2).required(),
  nin: Joi.string().trim().pattern(/^[0-9]{11}$/).required(),
});


const vitalSchema = Joi.object({
  recordedAt: Joi.date().iso(),

  bloodPressure: Joi.string().trim().max(20).allow(""),

  // Weight in kilograms.
  weight: Joi.number().min(0),

  // Height in centimetres.
  height: Joi.number().min(0),

  // Temperature in Celsius.
  temperature: Joi.number().min(0),

  // Pulse rate in beats per minute.
  pulse: Joi.number().min(0),

  // Respiratory rate.
  respiratoryRate: Joi.number().min(0),

  // Blood glucose measurement.
  bloodGlucose: Joi.number().min(0),

  // Required whenever blood glucose is supplied.
  bloodGlucoseUnit: Joi.string().valid("mmol/L", "mg/dL"),

  // Oxygen saturation percentage.
  oxygenSaturation: Joi.number().min(0).max(100),
})
  .with("bloodGlucose", "bloodGlucoseUnit")
  .with("bloodGlucoseUnit", "bloodGlucose");


const patientSchema = Joi.object({
  firstName: Joi.string().trim().min(2).max(50).required(),
  middleName: Joi.string().trim().max(50).allow(""),
  lastName: Joi.string().trim().min(2).max(50).required(),
  // Generated by the controller for compatibility.
  name: Joi.string().trim().min(3).max(150),
  nin: Joi.string().trim().pattern(/^[0-9]{11}$/).required(),
  // DOB replaces age during patient registration.
  dob: dobSchema.required(),
  gender: Joi.string().trim().lowercase().valid("male", "female").required(),
  email: Joi.string().trim().lowercase().email().allow(""),
  phone: Joi.string().trim().pattern(/^[0-9]{11}$/).required(),  
  address: Joi.string().trim().min(3).required(),
  stateOfOrigin: Joi.string().trim().min(2).required(),
  lgaOfOrigin: Joi.string().trim().min(2).required(),
  bloodGroup: Joi.string()
    .valid("A+", "A-", "B+", "B-", "AB+", "AB-", "O+", "O-")
    .required(),
  genotype: Joi.string()
    .valid("AA", "AS", "AC", "SS", "SC", "CC")
    .required(),
  nextOfKin: Joi.array().items(nextOfKinSchema),
  dateOfVisit: visitDate,
  dateOfVisits: Joi.array().items(visitDate).min(1),
  vitals: Joi.array().items(vitalSchema),
  diagnosis: Joi.string().trim().min(3).required(),
  treatment: Joi.string().trim().min(3).required(),
  notes: Joi.string().allow("").default(""),
})
  .or("dateOfVisit", "dateOfVisits")
  .unknown(false);

const updatePatientSchema = Joi.object({
  firstName: Joi.string().trim().min(2).max(50),
  middleName: Joi.string().trim().max(50).allow(""),
  lastName: Joi.string().trim().min(2).max(50),
  // DOB is optional when updating other patient details.
  dob: dobSchema,
  gender: Joi.string().trim().lowercase().valid("male", "female"),
  email: Joi.string().trim().lowercase().email().allow(""),
  phone: Joi.string().trim().pattern(/^[0-9]{11}$/), 
  nin: Joi.string().trim().pattern(/^[0-9]{11}$/).messages({"string.pattern.base": "NIN must contain exactly 11 digits.",}),  address: Joi.string().trim().min(3),
  stateOfOrigin: Joi.string().trim().min(2),
  lgaOfOrigin: Joi.string().trim().min(2),
  bloodGroup: Joi.string().valid(
    "A+", "A-", "B+", "B-", "AB+", "AB-", "O+", "O-"
  ),
  genotype: Joi.string().valid("AA", "AS", "AC", "SS", "SC", "CC"),
  nextOfKin: Joi.array().items(nextOfKinSchema),
  dateOfVisit: visitDate,
  dateOfVisits: Joi.array().items(visitDate).min(1),
  vitals: Joi.array().items(vitalSchema),
  diagnosis: Joi.string().trim().min(3),
  treatment: Joi.string().trim().min(3),
  notes: Joi.string().allow(""),
})
  .min(1)
  .unknown(false);

module.exports = {
  patientSchema,
  updatePatientSchema,
};